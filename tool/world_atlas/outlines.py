"""Offline country outlines from the same Natural Earth data as the atlas.

python3 -I tool/world_atlas/outlines.py COUNTRIES ZONE_TAB OUT
Regenerate alongside the atlas. Coordinates are simplified and quantized;
all countries keep their largest ring, including the very small ones.
"""
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate


def distance(point, start, end):
    dx, dy = end[0] - start[0], end[1] - start[1]
    if not dx and not dy:
        return math.hypot(point[0] - start[0], point[1] - start[1])
    t = max(0, min(1, ((point[0] - start[0]) * dx +
                       (point[1] - start[1]) * dy) / (dx * dx + dy * dy)))
    return math.hypot(point[0] - start[0] - t * dx,
                      point[1] - start[1] - t * dy)


def simplify(points, tolerance):
    if len(points) <= 2:
        return points
    index, farthest = max(
        ((i, distance(p, points[0], points[-1]))
         for i, p in enumerate(points[1:-1], 1)), key=lambda item: item[1])
    if farthest <= tolerance:
        return [points[0], points[-1]]
    return (simplify(points[:index + 1], tolerance)[:-1] +
            simplify(points[index:], tolerance))


def area(ring):
    return abs(sum(a[0] * b[1] - b[0] * a[1]
                   for a, b in zip(ring, ring[1:]))) / 2


def outlines(features, zone_tab):
    known = {generate.code_of(f['properties']) for f in features}
    cities = {code: (lat, lon) for code, lat, lon, _ in generate.zone_tab(zone_tab)
              if code not in known and code in generate.TERRITORY_NAMES}
    countries = {}
    for code, rings in generate.country_pieces(features, cities):
        countries.setdefault(code, []).extend(r for r, _ in rings)
    result = {}
    for code, rings in sorted(countries.items()):
        largest = max(rings, key=area)
        span = max(max(p[0] for p in largest) - min(p[0] for p in largest),
                   max(p[1] for p in largest) - min(p[1] for p in largest))
        tolerance = max(.0005, min(.06, span * .002))
        selected = sorted((r for r in rings if r is largest or area(r) >= .015),
                          key=area, reverse=True)
        cleaned = []
        for ring in selected:
            reduced = simplify(ring, tolerance)
            if len(reduced) < 4:
                reduced = ring
            rounded = [[round(x, 3), round(y, 3)] for x, y, *_ in reduced]
            if len({tuple(p) for p in rounded}) >= 3 and area(rounded) > 1e-9:
                cleaned.append(rounded)
        if cleaned:
            result[code] = cleaned
    return result


def base36(number):
    if number < 0:
        return '-' + base36(-number)
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    result = ''
    while number:
        number, remainder = divmod(number, 36)
        result = digits[remainder] + result
    return result or '0'


def encode(ring):
    previous = (0, 0)
    result = []
    for x, y, *_ in ring:
        point = (round(x * 1000), round(y * 1000))
        result.append(','.join(base36(a - b) for a, b in zip(point, previous)))
        previous = point
    return ';'.join(result)


def main(countries_path, zone_tab, out_path):
    data = outlines(json.load(open(countries_path))['features'], zone_tab)
    lines = ['// GENERATED by tool/world_atlas/outlines.py. Do not edit by hand.',
             '// Natural Earth 1:50m, public domain. Offline display geometry.',
             '', '/// Base-36 delta coordinates in 1/1000 degree; | separates closed rings.',
             'const countryOutlines = <String, String>{']
    for code, rings in data.items():
        encoded = '|'.join(encode(ring) for ring in rings)
        lines.append(f"  '{code}': '{encoded}',")
    Path(out_path).write_text('\n'.join(lines + ['};', '']))


if __name__ == '__main__':
    main(*sys.argv[1:])
